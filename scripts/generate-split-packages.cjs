// Generate per-platform split packages under npm-split/.
//
// Each split package is named `@ylcc/napi-blitz-<platform>-split` and
// contains the full JS API (dist/) plus a native/ directory with the
// .node binary and a direct-loading index.js.  The dist/ is copied
// verbatim from the main package -- no patches needed because
// dist/native.js already does `require("./native/index.js")` relative
// to the package root, and that's exactly what we provide.
//
// Run after `napi artifacts` and `pnpm run build:ts`.

const fs = require('node:fs');
const path = require('node:path');

const rootDir = path.resolve(__dirname, '..');
const packageJson = require('../package.json');
const version = packageJson.version;
const napiConfig = packageJson.napi;
const binaryName = napiConfig.binaryName;
const npmDir = path.join(rootDir, 'npm');
const splitDir = path.join(rootDir, 'npm-split');
const distDir = path.join(rootDir, 'dist');
const nativeDir = path.join(rootDir, 'native');

// target -> { platformName, nodeFile, os, cpu }
const platforms = [];

for (const target of napiConfig.targets) {
  const parts = target.split('-');
  const arch = parts[0];

  let platformName;
  let os;
  let cpu;
  let libc;

  if (target.includes('apple-darwin')) {
    const darwinArch = arch === 'aarch64' ? 'arm64' : 'x64';
    platformName = `darwin-${darwinArch}`;
    os = 'darwin';
    cpu = darwinArch;
  } else if (target.includes('unknown-linux-gnu')) {
    const linuxArch = arch === 'aarch64' ? 'arm64' : 'x64';
    platformName = `linux-${linuxArch}-gnu`;
    os = 'linux';
    cpu = linuxArch;
    libc = 'glibc';
  } else if (target.includes('unknown-linux-musl')) {
    const linuxArch = arch === 'aarch64' ? 'arm64' : 'x64';
    platformName = `linux-${linuxArch}-musl`;
    os = 'linux';
    cpu = linuxArch;
    libc = 'musl';
  } else if (target.includes('pc-windows-msvc')) {
    const winArch = arch === 'aarch64' ? 'arm64' : 'x64';
    platformName = `win32-${winArch}-msvc`;
    os = 'win32';
    cpu = winArch;
  } else if (target.includes('unknown-freebsd')) {
    platformName = `freebsd-x64`;
    os = 'freebsd';
    cpu = 'x64';
  } else {
    continue;
  }

  const nodeFile = `${binaryName}.${platformName}.node`;

  platforms.push({
    target,
    platformName,
    nodeFile,
    os,
    cpu,
    libc,
  });
}

function generatePackageJson(platform) {
  const pkg = {
    name: `@ylcc/napi-blitz-${platform.platformName}-split`,
    version,
    description: packageJson.description,
    main: 'dist/index.js',
    types: 'dist/index.d.ts',
    files: ['dist/', 'native/'],
    os: [platform.os],
    cpu: [platform.cpu],
    keywords: packageJson.keywords,
    license: packageJson.license,
    engines: packageJson.engines,
    repository: packageJson.repository,
    publishConfig: packageJson.publishConfig,
  };

  if (platform.libc) {
    pkg.libc = [platform.libc];
  }

  return pkg;
}

// native/index.js that loads the .node file directly.
// No process.platform / process.arch branching -- just a direct require.
function generateNativeIndexJs(platform) {
  return `// @ts-nocheck
/* auto-generated by generate-split-packages.cjs */
// Direct platform binding for ${platform.platformName}.
// Replaces the main package's native/index.js which performs runtime
// platform/arch detection.  Here we load the .node file directly.

module.exports = require('./${platform.nodeFile}');
`;
}

function copyDirRecursive(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

// ---- main ----

if (!fs.existsSync(npmDir)) {
  console.error(`npm/ directory not found at ${npmDir}. Run \`napi artifacts\` first.`);
  process.exit(1);
}

if (!fs.existsSync(distDir)) {
  console.error(`dist/ directory not found at ${distDir}. Run \`pnpm run build:ts\` first.`);
  process.exit(1);
}

// Clean previous output
if (fs.existsSync(splitDir)) {
  fs.rmSync(splitDir, { recursive: true });
}
fs.mkdirSync(splitDir, { recursive: true });

const nativeDts = path.join(nativeDir, 'index.d.ts');
const nativeDtsContent = fs.readFileSync(nativeDts, 'utf8');

let generated = 0;

for (const platform of platforms) {
  const sourceNodePath = path.join(npmDir, platform.platformName, platform.nodeFile);
  if (!fs.existsSync(sourceNodePath)) {
    console.warn(`SKIP ${platform.platformName}: .node file not found at ${sourceNodePath}`);
    continue;
  }

  const pkgDir = path.join(splitDir, platform.platformName);
  fs.mkdirSync(pkgDir, { recursive: true });

  // native/ directory: .node file + direct-loading index.js + index.d.ts
  const pkgNativeDir = path.join(pkgDir, 'native');
  fs.mkdirSync(pkgNativeDir, { recursive: true });
  fs.copyFileSync(sourceNodePath, path.join(pkgNativeDir, platform.nodeFile));
  fs.writeFileSync(path.join(pkgNativeDir, 'index.js'), generateNativeIndexJs(platform));
  fs.writeFileSync(path.join(pkgNativeDir, 'index.d.ts'), nativeDtsContent);

  // dist/ directory: copy verbatim (dist/native.js already resolves ./native/index.js)
  copyDirRecursive(distDir, path.join(pkgDir, 'dist'));

  // package.json
  fs.writeFileSync(
    path.join(pkgDir, 'package.json'),
    JSON.stringify(generatePackageJson(platform), null, 2) + '\n',
  );

  // README.md
  fs.writeFileSync(
    path.join(pkgDir, 'README.md'),
    `# \`@ylcc/napi-blitz-${platform.platformName}-split\`\n\nThis is the **${platform.target}** binary for \`@ylcc/napi-blitz\` with direct loading (no runtime platform detection).\n`,
  );

  generated++;
  console.log(`Generated @ylcc/napi-blitz-${platform.platformName}-split`);
}

console.log(`\nDone. ${generated} split packages generated under ${splitDir}/`);
